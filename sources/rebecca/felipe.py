# Parâmetros da simulação
num_points = 100  # quantidade de pontos na órbita
start_date = datetime.datetime(2025, 6, 5, 20, 5, 30)
delta_t = 90 * 60 / num_points  # passo em segundos (~90min)

# Loop para cada TLE
for idx, (line1, line2) in enumerate(tles):
    # Inicializa o satélite
    satellite = Satrec.twoline2rv(line1, line2)

    # Extrai o NORAD ID para nome do arquivo
    norad_id = line1.split()[1]

    # Lista para armazenar os dados
    data = []

    # Simulação da órbita
    for i in range(num_points):
        current_time = start_date + datetime.timedelta(seconds=i * delta_t)
        jd, fr = jday(
            current_time.year, current_time.month, current_time.day,
            current_time.hour, current_time.minute, current_time.second + current_time.microsecond / 1e6
        )

        e, r, v = satellite.sgp4(jd, fr)

        if e == 0:
            x, y, z = r
            lat = np.degrees(np.arcsin(z / np.linalg.norm(r)))
            lon = np.degrees(np.arctan2(y, x))
            alt_km = np.linalg.norm(r) - 6371

            # Ano decimal
            year = current_time.year
            day_of_year = current_time.timetuple().tm_yday + (current_time.hour / 24)
            yeardec = year + (day_of_year / 365.25)

            # Campo magnético
            mag = wmm2020.wmm(lat, lon, alt_km, yeardec)

            # Armazena os valores convertidos para Gauss
            data.append([
                current_time.isoformat(),
                mag["east"].values.item() * 1e-5,
                mag["north"].values.item() * 1e-5,
                mag["down"].values.item() * 1e-5
            ])
        else:
            print(f"Erro na propagação SGP4 em {current_time}: código {e}")

    # Nome do arquivo
    filename = f"campo_magnetico_{norad_id}.csv"

    # Salva em CSV
    with open(filename, mode="w", newline="") as file:
        writer = csv.writer(file)
        writer.writerow(["Tempo (UTC)", "East (G)", "North (G)", "Down (G)"])
        writer.writerows(data)

    print(f"Dados salvos em '{filename}'")


